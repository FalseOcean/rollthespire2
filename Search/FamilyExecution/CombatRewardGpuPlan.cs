internal sealed record CombatRewardGpuPlan(uint[] Meta, uint[] Pools, uint[] Ids, uint[] Predicates,
    uint[] Targets, Beta110GpuCombatRewardHotLoopPlan HotLoop, int Routes)
{
    internal GpuNumericalVariant NumericalVariant { get; init; }
    internal GpuNumericRequirements NumericRequirements => GpuIntegerNumerics.Requirements(NumericalVariant);
    internal bool UsesHotLoop => HotLoop.Enabled;
    internal bool UsesOpeningPrefixHotLoop { get; init; }
    internal bool UsesDenseCarry8 { get; init; }
    internal bool NeedsCompleteMatchingReference { get; init; }
    internal bool ChecksCardCollection { get; init; }
    // Historical MP-C2 metadata retained for old evidence formatters. The
    // query-literal body allocates no Capsule bag and has no capacity variant.
    internal const bool FactoryExactBagCapacity = true;
    internal bool ExactBagCapacity { get; init; }
    internal string BagCapacityRevision => BagCapacity != 512
        ? ".ExactBagCapacity.20261016.v1.Slot" + Meta[2] + ".Entries" + BagCapacity : "";
    // Stable old empty-bag shape value; no bag storage is generated by C.
    internal int BagCapacity => 512;
    internal bool UsesQueryLiteralPartyOpening { get; init; }
    internal uint[] ObservedOpeningData { get; init; } = [];
    internal uint[] ObservedBonesIds { get; init; } = [];
    internal bool UsesObservedOpening => ObservedOpeningData.Length > 0;
    private bool SharesObservedBonesPair => UsesChildShuffle && Routes == 2 && UsesObservedOpening && ObservedOpeningData[1] != 0;
    internal bool UsesObservedOpeningHotLoop => UsesObservedOpening && UsesHotLoop;
    internal bool UsesLazyObservedBag => ObservedOpeningData.Length > 10 && ObservedOpeningData[10] != 0;
    private OpeningReplay? OpeningReplayMask { get; init; }
    internal bool UsesOpeningReplayCrop => OpeningReplayMask.HasValue;
    internal bool UsesGenericDirectCardPool { get; init; }
    internal bool UsesUnobservedCardBurn { get; init; }
    internal bool UsesNeutralWitness { get; init; }
    internal bool UsesChildShuffle { get; init; }
    internal string TerminalCardGateSource { get; init; } = "";
    internal bool UsesTerminalCardGate => TerminalCardGateSource.Length != 0;
    internal bool UsesCardFreeTerminal { get; init; }
    internal string Revision(bool compact) => "C.CombatReward.Gpu." + (UsesHotLoop ? "NeutralHotLoop" : "GenericStreaming.EmptyExclusionDirect.20261013.v1") +
        (UsesNeutralWitness ? CombatRewardNeutralWitness.Revision : "") +
        (UsesObservedOpening ? CombatRewardObservedOpening.Revision + ".BucketCapacity" + ObservedOpeningData[8] : "") +
        (SharesObservedBonesPair ? ".SharedDynamicBonesPair.20261121.v1" : "") +
        (UsesObservedOpeningHotLoop ? ".ActualHotOrExact.20261102.v1" : "") +
        (UsesLazyObservedBag ? ".LazyObservedCapsuleLanes.20261115.v1" : "") +
        (OpeningReplayMask is { } opening ? ".OpeningReplayCrop.20261115.v1.Group" + (int)opening : "") +
        (UsesGenericDirectCardPool ? ".GenericDirectOrdinaryCards.20261115.v1" : "") +
        (UsesUnobservedCardBurn ? ".UnobservedCardBurn.20261115.v1" : "") +
        (UsesTerminalCardGate ? ".TerminalCardCapacity.20261015.v1" : "") +
        (UsesCardFreeTerminal ? ".CardFreeTerminal.20261114.v1" : "") +
        (NeedsCompleteMatchingReference ? ".CompletePositiveMatching.20261026.v1" : "") +
        (ChecksCardCollection ? ".CardCollection.20261105.v1" : "") +
        (UsesQueryLiteralPartyOpening ? ".PartyQueryLiteralOpening.20261027.v1" : "") +
        (UsesOpeningPrefixHotLoop ? ".QueryLiteralPrefixHotLoop.20261029.v1" : "") +
        (HotLoop.RareOnlyIdentityElisionEnabled ? ".RareOnlyIdentityBurn.20261030.v2" : "") +
        (HotLoop.UnobservedFixedGoldEnabled ? ".UnobservedFixedGold.20261031.v1" : "") +
        (HotLoop.AssignmentEarlyRejectionEnabled ? ".AssignmentEarly.20261030.v1" : "") +
        (!compact && UsesDenseCarry8 ? ".DenseCarry8.20261030.v1" : "") +
        BagCapacityRevision +
        (compact ? ".CompactAbi1" : ".Dense") + ".CanonicalAbi1Ready.20260907.v1" +
        (NumericalVariant == GpuNumericalVariant.IntegerRne ? ".IntegerRne.20261025.v1" : "") +
        (UsesChildShuffle ? ".Modern113" : "") + NeowIdentityOfferFacts.Revision + GpuRngRotation.Revision;

    internal static CombatRewardGpuPlan? TryCreate(SearchModel request, CombatRewardReplay replay, out string issue,
        bool? openingPrefixHotLoop = null, bool? rareOnlyIdentityElision = null, bool? assignmentEarlyRejection = null,
        bool? unobservedFixedGold = null, bool? genericDirectCardPool = null, bool? openingReplayCrop = null,
        bool? unobservedCardBurn = null)
    {
        issue = "";
        var reward = replay.Plan;
        // Physical bounds of the retained donor, not Search admission gates.
        if (!RuntimeProfilePolicies.UsesBeta110SharedAlgorithms(request.ProfileId)) issue = "RootCodecOutsideDonor";
        else if (reward.PredicateCount > 64) issue = "PredicateMaskCapacity";
        else if (replay.UsesObservedOpening && replay.ObservedOpening!.BagCapacity > 512) issue = "ObservedOpeningBagCapacity";
        else if (replay.UsesObservedOpening && reward.OpeningConsumption.ReplayBonesOffer && replay.ObservedOpening!.BonesIds.Length > 64) issue = "ObservedOpeningBonesCapacity";
        else if (reward.OpeningConsumption.OrderedRelicIds.Contains(Beta110FastRelicCatalog.Kaleidoscope) &&
            !replay.KaleidoscopeCountOnly && replay.Catalog.OtherCharacterPools.Length > 15) issue = "KaleidoscopePermutationCapacity";
        if (issue.Length != 0) return null;
        var catalog = replay.Catalog with { OrdinaryRelics = [], PlayerRelicBuckets = [], SharedRelicConsumeShuffleLengths = [] };
        var policy = Beta110GpuCombatRewardRoutePolicy.UnpinnedAssumeUnperturbed;
        bool prefixTrial = openingPrefixHotLoop ?? CaptureOpeningPrefixTrial();
        bool observedHotTrial = replay.UsesObservedOpening && CaptureObservedHotTrial();
        // This temporary numerical shape prepares the existing neutral suffix's
        // tables. The actual opening and held state are still replayed, then
        // checked against every hot-state premise before any rejection.
        var hotReward = observedHotTrial ? reward with {
            ExplicitContext = Beta110CombatRewardExplicitContext.Empty(request.ProfileId)
        } : reward;
        var hot = Beta110GpuCombatRewardHotLoopCompiler.Compile(request.Ascension, hotReward, catalog, policy,
            allowOpeningPrefix: prefixTrial,
            allowUnobservedFixedGold: request.Authority.PlayersCount == 1 &&
                (unobservedFixedGold ?? CaptureFollowupTrial("RT2_C_FIXED_GOLD_HOT")));
        if (replay.UsesObservedOpening && !observedHotTrial)
            hot = Beta110GpuCombatRewardHotLoopPlan.Disabled("ObservedOpeningHasSeedDependentHeldRewardStructure");
        var targetTrial = CombatRewardTargetOptimizations.Capture();
        hot = CombatRewardTargetOptimizations.Apply(hot, reward, catalog,
            rareOnlyIdentityElision ?? targetTrial.RareOnly, assignmentEarlyRejection ?? targetTrial.Assignment);
        bool denseCarry8 = CaptureDenseTrial();
        uint[] meta = CombatRewardGpuPacking.BuildPlanMeta(request.Authority.PlayerSlotIndex,
            request.Authority.PlayersCount, request.Ascension, request.Authority.AllCharacterCardPoolsUnlocked == true,
            request.Authority.IsScrollBoxesAllowed == true, request.CharacterKey == BaseGameModelKeys.Characters.Defect,
            request.Authority.EffectAuthority?.BonesEligibleRelics?.Count(k => k != BaseGameModelKeys.Relics.NeowsBones) ?? 0,
            reward, 0x43463031, catalog, policy, 255, 255, 255, hot, replay.PrecedingNicheDraws,
            replay.CapsuleNicheAdvances, replay.KaleidoscopeCountOnly, replay.ConservativelyKeeps);
        if (replay.UsesChildShuffle)
        {
            meta[16] = (uint)NeowFamilyReplay.NonCombatHash;
            meta[17] = (uint)(NeowFamilyReplay.NonCombatHash >> 32);
        }
        if (replay.NeutralWitness is { } proof)
        {
            meta[51] = proof.Available ? proof.RequiresAllOffers ? 2u : 1u : 3u;
            meta[52] = proof.NeutralMask;
        }
        uint[] pools = CombatRewardGpuPacking.BuildPoolMeta(catalog, out uint[] ids);
        uint[] predicates = CombatRewardGpuPacking.BuildPredicates(reward, out uint[] targets);
        bool canUseDirectCardPools = replay.UsesChildShuffle && !hot.Enabled && !replay.ConservativelyKeeps &&
            reward.CardPoolAuthorityExact && HasDirectOrdinaryCardPools(catalog.CombatRewardCardPool);
        return new(meta, pools, ids, predicates, targets, hot, replay.RouteCount) {
            UsesNeutralWitness = replay.UsesNeutralWitness,
            UsesChildShuffle = replay.UsesChildShuffle,
            UsesGenericDirectCardPool = canUseDirectCardPools &&
                (genericDirectCardPool ?? CaptureFollowupTrial("RT2_C_GENERIC_DIRECT_CARD_POOL")),
            UsesUnobservedCardBurn = canUseDirectCardPools && !reward.CollectionFilterRequested &&
                reward.CardAssignmentTargets.Length == 0 && reward.Predicates.All(predicate => !predicate.HasCardPredicate) &&
                (unobservedCardBurn ?? CaptureFollowupTrial("RT2_C_UNOBSERVED_CARD_BURN")),
            ObservedOpeningData = replay.UsesObservedOpening ? replay.ObservedOpening!.GpuData : [],
            ObservedBonesIds = replay.UsesObservedOpening ? replay.ObservedOpening!.BonesIds.Select(id => (uint)id).ToArray() : [],
            OpeningReplayMask = replay.UsesChildShuffle && !replay.ConservativelyKeeps &&
                replay.ObservedOpening is { Available: true, DynamicBones: false } &&
                (openingReplayCrop ?? CaptureFollowupTrial("RT2_C_OPENING_REPLAY_CROP"))
                    ? FixedOpeningReplayMask(reward.OpeningConsumption.OrderedRelicIds, replay.IsMultiplayer) : null,
            NeedsCompleteMatchingReference = reward.NeedsCompleteMatchingReference,
            ChecksCardCollection = reward.CollectionFilterCovered,
            UsesQueryLiteralPartyOpening = replay.UsesQueryLiteralPartyOpening,
            UsesOpeningPrefixHotLoop = hot.Enabled && !replay.UsesObservedOpening && reward.OpeningConsumption.HasReplay && prefixTrial,
            UsesDenseCarry8 = denseCarry8,
            ExactBagCapacity = FactoryExactBagCapacity,
            UsesCardFreeTerminal = replay.CanUsePotionPrefix && !replay.ConservativelyKeeps &&
                reward.CardAssignmentTargets.Length == 0 && HasFaultFreeOrdinaryCardGroup(catalog),
            TerminalCardGateSource = CompileTerminalCardGate(request, replay, hot.Enabled)
        };
    }

    [Flags]
    private enum OpeningReplay
    {
        None = 0,
        RareCards = 1,
        Kaleidoscope = 2,
        Paperweight = 4,
        Coffer = 8,
        MultiplayerScroll = 16,
        ScrollBoxes = 32
    }

    // Fixed observed routes contain at most two top-level grants. Their order
    // stays in the plan buffer. Nested Capsule pickups use capability data and
    // never dispatch a top-level replay opcode. Dynamic Bones retains the donor.
    private static OpeningReplay FixedOpeningReplayMask(byte[] relics, bool multiplayer)
    {
        OpeningReplay mask = OpeningReplay.None;
        foreach (byte relic in relics)
            mask |= relic switch
            {
                Beta110FastRelicCatalog.HeftyTablet or Beta110FastRelicCatalog.ArcaneScroll => OpeningReplay.RareCards,
                Beta110FastRelicCatalog.Kaleidoscope => OpeningReplay.Kaleidoscope,
                Beta110FastRelicCatalog.LeadPaperweight => OpeningReplay.Paperweight,
                Beta110FastRelicCatalog.LostCoffer => OpeningReplay.Coffer,
                Beta110FastRelicCatalog.MassiveScroll when multiplayer => OpeningReplay.MultiplayerScroll,
                Beta110FastRelicCatalog.ScrollBoxes => OpeningReplay.ScrollBoxes,
                _ => OpeningReplay.None
            };
        return mask;
    }

    private string OpeningReplayDefines() => OpeningReplayMask is { } mask
        ? "\n#define RT2_C_OPENING_REPLAY_CROP 1\n" +
          ((mask & OpeningReplay.RareCards) != 0 ? "#define RT2_C_OPENING_RARE_CARDS 1\n" : "") +
          ((mask & OpeningReplay.Kaleidoscope) != 0 ? "#define RT2_C_OPENING_KALEIDOSCOPE 1\n" : "") +
          ((mask & OpeningReplay.Paperweight) != 0 ? "#define RT2_C_OPENING_PAPERWEIGHT 1\n" : "") +
          ((mask & OpeningReplay.Coffer) != 0 ? "#define RT2_C_OPENING_COFFER 1\n" : "") +
          ((mask & OpeningReplay.MultiplayerScroll) != 0 ? "#define RT2_C_OPENING_MULTIPLAYER_SCROLL 1\n" : "") +
          ((mask & OpeningReplay.ScrollBoxes) != 0 ? "#define RT2_C_OPENING_SCROLL_BOXES 1\n" : "")
        : "";

    // Bounded FT02 experiment; it is not the selected production default.
    private static bool CaptureObservedHotTrial() => Environment.GetEnvironmentVariable("RT2_C_OBSERVED_HOT_EXPERIMENT") switch {
        null or "" or "off" => false,
        "on" => true,
        var mode => throw new InvalidOperationException("C.UnknownObservedHotExperiment:" + mode)
    };

    // Capture once with the immutable query plan. Each optimization retains its
    // own numerical/structure guards; explicit off remains a diagnostic control.
    private static bool CaptureOpeningPrefixTrial() => Environment.GetEnvironmentVariable("RT2_C_PREFIX_EXPERIMENT") switch {
        null or "" or "default" => true,
        "off" => false,
        "hot" => true,
        var mode => throw new InvalidOperationException("C.UnknownPrefixExperiment:" + mode)
    };

    private static bool CaptureDenseTrial() => Environment.GetEnvironmentVariable("RT2_C_DENSE_EXPERIMENT") switch {
        null or "" or "default" => true,
        "off" => false,
        "carry8" => true,
        var mode => throw new InvalidOperationException("C.UnknownDenseExperiment:" + mode)
    };

    private static bool CaptureFollowupTrial(string variable) => Environment.GetEnvironmentVariable(variable) switch {
        "off" => false,
        null or "" or "default" or "on" => true,
        var mode => throw new InvalidOperationException("C.UnknownFollowupExperiment:" + variable + ":" + mode)
    };

    private static string CompileTerminalCardGate(SearchModel request, CombatRewardReplay replay, bool hot)
    {
        var plan = replay.Plan;
        if (hot || request.Authority.PlayersCount != 1 || replay.ConservativelyKeeps ||
            !plan.CardPoolAuthorityExact) return "";
        if (!HasFaultFreeOrdinaryCardGroup(replay.Catalog)) return "";
        var targets = new Dictionary<ushort, ulong>();
        for (int i = 0; i < plan.Predicates.Length; i++)
        {
            var row = plan.Predicates[i];
            if (!row.HasCardPredicate) continue;
            if (!row.IsAnyBattle || row.CardAny.Length + row.CardAll.Length != 1 || row.CardBan.Length != 0 ||
                row.HasPotionDropPredicate || row.HasPotionIdentityPredicate || row.HasGoldPredicate) return "";
            ushort target = row.CardAny.Length == 1 ? row.CardAny[0] : row.CardAll[0];
            targets[target] = targets.GetValueOrDefault(target) | (1UL << i);
        }
        // One target cannot run out of slots before the original last draw.
        // Keep this first measured specialization bounded to small target sets.
        if (targets.Count is < 2 or > 6) return "";
        var source = new System.Text.StringBuilder("#ifndef RT2_C_TERMINAL_CARD_GATE\n#define RT2_C_TERMINAL_CARD_GATE 1\n#endif\n#if RT2_C_TERMINAL_CARD_GATE\nuint cr_terminal_card_missing(uint64_t matched){uint missing=0u;");
        int bit = 0;
        foreach (var (_, mask) in targets)
            source.Append($"if((matched&uint64_t(0x{mask:X}ul))==uint64_t(0u))missing|={1u << bit++}u;");
        source.Append("return missing;}\nuint cr_terminal_card_seen(uint missing,uint value){");
        bit = 0;
        foreach (var (target, _) in targets)
            source.Append($"if(value=={target}u)missing&=~{1u << bit++}u;");
        return source.Append("return missing;}\n#endif\n").ToString();
    }

    // Three distinct valid identities across the fallback pools guarantee
    // the ordinary three-card group without constraining the rarity rolls.
    private static bool HasFaultFreeOrdinaryCardGroup(Beta110FastEffectCatalog catalog)
    {
        var pool = catalog.CombatRewardCardPool;
        ushort[] ids = pool.Common.Concat(pool.Uncommon).Concat(pool.Rare).Distinct().ToArray();
        return ids.Length >= 3 && !ids.Contains(Beta110FastDenseId.Invalid);
    }

    private static bool HasDirectOrdinaryCardPools(Beta110FastCardPool pool)
    {
        // A three-card group excludes at most two original ranks. Each lane
        // can always supply the next card, and a pick excludes only its own lane.
        var ids = new HashSet<ushort> { Beta110FastDenseId.Invalid };
        return pool.Common.Length >= 3 && pool.Uncommon.Length >= 3 && pool.Rare.Length >= 3 &&
            pool.Common.Concat(pool.Uncommon).Concat(pool.Rare).All(ids.Add);
    }

    internal string ShaderSource(bool forceGeneric = false)
    {
        string source = FamilyGpuComputeUtility.LoadEmbeddedShader("CombatRewardFamily.comp.glsl")
        .Replace("/*__C_OBSERVED_OPENING__*/", UsesObservedOpening
            ? "#define RT2_C_OBSERVED_OPENING 1\n#define RT2_C_OBSERVED_HOT " + (UsesObservedOpeningHotLoop ? "1\n" : "0\n") +
              "#define RT2_C_SHARED_BONES_PAIR " + (SharesObservedBonesPair && !forceGeneric ? "1\n" : "0\n") +
              "#define RT2_C_LAZY_OBSERVED_BAG " + (UsesLazyObservedBag ? "1\n" : "0\n") +
              "#define RT2_C_BAG_CAPACITY " + Math.Max(1, ObservedOpeningData[8]) + "\n" +
              FamilyGpuComputeUtility.LoadEmbeddedShader("CombatRewardOpening.glsl")
            : "#define RT2_C_OBSERVED_OPENING 0\n", StringComparison.Ordinal)
        .Replace("/*__C_DENSE_HELPERS__*/", UsesDenseCarry8 ?
            "uint64_t make_u64(uint lo,uint hi){return cr_make_u64(lo,hi);}\n" +
            "uint64_t rotl64(uint64_t x,uint n){return cr_rotl64(x,n);}\n" +
            FamilyGpuComputeUtility.LoadEmbeddedShader("VisibleSeedRootHashCommon.glsl") : "", StringComparison.Ordinal)
        .Replace("/*__C_TERMINAL_CARD_GATE__*/", TerminalCardGateSource, StringComparison.Ordinal)
        .Replace("/*__C_CAPSULE_DEFINES__*/", "#define RT2_C_ASSIGNMENT " + (Meta[56] + Meta[59] > 0 ? "1\n" : "0\n") +
            "#define RT2_C_MULTIPLAYER " + (Meta[3] > 1 ? "1\n" : "0\n") +
            "#define RT2_C_CARD_FREE_TERMINAL " + (UsesCardFreeTerminal ? "1\n" : "0\n") +
            (UsesGenericDirectCardPool && !forceGeneric ? "#define RT2_C_GENERIC_DIRECT_CARD_POOL 1\n" : "") +
            (UsesUnobservedCardBurn && !forceGeneric ? "#define RT2_C_UNOBSERVED_CARD_BURN 1\n" : "") +
            "#define RT2_C_MODERN113 " + (UsesChildShuffle ? "1" : "0") +
            (forceGeneric ? "" : OpeningReplayDefines()), StringComparison.Ordinal)
        .Replace("/*__C_HOT_DEFINES__*/", "#define RT2_C_DENSE_CARRY8 " + (UsesDenseCarry8 ? "1\n" : "0\n") +
            "#define RT2_C_HOT_OPENING_PREFIX " + (UsesOpeningPrefixHotLoop ? "1\n" : "0\n") +
            Beta110GpuCombatRewardHotLoopCompiler.BuildShaderDefines(HotLoop,
            Beta110GpuCombatRewardRoutePolicy.UnpinnedAssumeUnperturbed, forceGeneric ? Beta110GpuCombatRewardHotLoopVariant.Disabled :
            Beta110GpuCombatRewardHotLoopVariant.OptimizedSingleRoute), StringComparison.Ordinal)
        .Replace("/*__C_COMMON__*/", FamilyGpuComputeUtility.LoadEmbeddedShader("Beta110GpuCombatRewardCommon.glsl"), StringComparison.Ordinal)
        .Replace("/*__C_STREAMING__*/", FamilyGpuComputeUtility.LoadEmbeddedShader("Beta110GpuCombatRewardStreamingP10A.glsl"), StringComparison.Ordinal);
        // Pinned sources retain the original entry function and source bytes:
        // there is no reachable guard, disabled branch or extra wrapper to alter
        // their module identity/startup cost. The proof exists only in no-N code.
        source = source.Replace("/*__C_NEUTRAL_WITNESS__*/", UsesNeutralWitness ?
            CombatRewardNeutralWitness.ShaderGuard : "", StringComparison.Ordinal);
        if (UsesNeutralWitness)
            source = source.Replace("bool c_keep_root(uint64_t root){", "bool c_numeric_keep_root(uint64_t root){",
                StringComparison.Ordinal).Replace("bool c_keep_root_proven(uint64_t root){", "bool c_keep_root(uint64_t root){",
                    StringComparison.Ordinal);
        return NumericalVariant switch
        {
            GpuNumericalVariant.NativeFloat64 => source,
            GpuNumericalVariant.IntegerRne => CombatRewardIntegerSource.Adapt(source),
            _ => throw new InvalidOperationException("C.UnknownGpuNumericalVariant")
        };
    }
