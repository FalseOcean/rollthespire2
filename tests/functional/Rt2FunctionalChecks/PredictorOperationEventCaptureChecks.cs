    internal static void Run(RunState native, PredictorCatalog catalog)
    {
        var player = LocalContext.GetMe(native)!;
        bool previousTestMode = TestMode.IsOn;
        var originalPotions = player.PotionSlots.ToArray();
        var fixtureRelics = new[] { "ANCHOR", "BLOOD_VIAL", "HAPPY_FLOWER", "PEN_NIB", "ODDLY_SMOOTH_STONE",
            "DREAM_CATCHER", "TINY_MAILBOX", "WHITE_BEAST_STATUE" }
            .Select(key => ModelDb.GetById<RelicModel>(new("RELIC", key)).ToMutable()).ToArray();
        TestMode.IsOn = true;
        try
        {
            CheckPotionTargets(native, player);
            CheckMendTargets(native, player);
            foreach (var relic in fixtureRelics) player.AddRelicInternal(relic, silent: true);
            // This fixture begins in the shop-capture setup at floor zero.
            // Event child combat requires a run that has passed its opening.
            while (native.TotalFloor < 7)
                native.AppendToMapPointHistory(MegaCrit.Sts2.Core.Map.MapPointType.Unknown,
                    MegaCrit.Sts2.Core.Rooms.RoomType.Event, new ModelId("EVENT", "BRAIN_LEECH"));
            foreach (var potion in player.Potions.ToArray()) player.DiscardPotionInternal(potion, silent: true);
            var choices = ModelDb.AllPotions.Where(p => p.Rarity.ToString() is "Common" or "Uncommon").Take(2).ToArray();
            foreach (var potion in choices) player.AddPotionInternal(potion.ToMutable(), silent: true);
            foreach (string row in InitialPages)
            {
                var parts = row.Split('|');
                var ev = (EventModel)ModelDb.GetById<EventModel>(new("EVENT", parts[0])).ToMutable();
                var synchronizer = new EventCombatSynchronizer(native, native);
                // Setup belongs to this isolated native fixture. Capture itself
                // must never invoke this lifecycle or consume any native RNG.
                ev.BeginEvent(player, synchronizer, false).GetAwaiter().GetResult();
                try
                {
                    if (parts[0] == "RELIC_TRADER")
                        Set(ev, "_newRelics", new RelicModel[]
                        {
                            ModelDb.GetById<RelicModel>(new("RELIC", "ALCHEMICAL_COFFER")),
                            ModelDb.GetById<RelicModel>(new("RELIC", "WHETSTONE")),
                            ModelDb.GetById<RelicModel>(new("RELIC", "WAR_PAINT"))
                        });
                    string before = Stamp(native, ev);
                    var scene = (PredictorOperationEventScene)PredictorOperationEventCapture.Capture(native, ev, catalog);
                    Require(Stamp(native, ev) == before, parts[0] + " capture mutated native state");
                    string[] allowed = parts[1].Split(',');
                    Require(scene.Options.Length == ev.CurrentOptions.Count && scene.Options.All(o => allowed.Any(a =>
                        a.EndsWith(':') || a.EndsWith('_') ? o.Key.StartsWith(a, StringComparison.Ordinal) : o.Key == a)),
                        parts[0] + " current source labels: " + string.Join(",", scene.Options.Select(o => o.Key)));
                    Require(scene.Options.Zip(ev.CurrentOptions).All(pair => pair.First.Enabled == !pair.Second.IsLocked),
                        parts[0] + " captured option legality changed");
                    Require(scene.Rng == CrystalSphereLiveCapture.RngState(PredictorStream.Niche, ev.Rng), parts[0] + " RNG differs");
                    var baseline = PredictorOperationCapture.Capture(native, "0.111.0");
                    foreach (var option in scene.Options.Where(o => o.Enabled))
                    {
                        PredictorOperationResult result;
                        try { result = PredictorOperation.Preview(baseline with { Scene = scene }, new ChooseEventOption(option.Key)); }
                        catch (Exception ex) { throw new InvalidOperationException("OPERATION_EVENT_CAPTURE source=" + parts[0] +
                            ";option=" + option.Key + ";detached source calculation failed", ex); }
                        Require(result.Disposition == PredictorInputResult.Accepted,
                            parts[0] + " original current enabled option rejected: " + option.Key + "/" + result.Disposition);
                        Require(Stamp(native, ev) == before, parts[0] + " detached action changed native fixture");
                    }
                    CheckLiveProjection(baseline with { Scene = scene }, ev);
                    Require(Stamp(native, ev) == before, parts[0] + " projection changed native fixture");
                    Progressed(native, ev, catalog, scene);
                }
                finally { ev.EnsureCleanup(); }
            }
        }
        finally
        {
            foreach (var relic in fixtureRelics) player.RemoveRelicInternal(relic, silent: true);
            foreach (var potion in player.Potions.ToArray()) player.DiscardPotionInternal(potion, silent: true);
            for (int slot = 0; slot < originalPotions.Length; slot++)
                if (originalPotions[slot] is { } potion) player.AddPotionInternal(potion, slot, silent: true);
            TestMode.IsOn = previousTestMode;
        }
        Console.WriteLine("OPERATION_EVENT_CAPTURE original 34 initial pages + Ranwid/Trader/Mushroom/Lantern projection + Bridge/Tablet/Conveyor/Tinker/Trial/Future stages PASS (isolated native fixtures)");
    }

    private static void CheckLiveProjection(PredictorOperationSnapshot snapshot, EventModel ev)
    {
        static OperationPreviewRow[] Rows(OperationPreview preview) => preview.Branches.SelectMany(b => b.Sections)
            .SelectMany(s => s.Rows).ToArray();
        OperationPreview Preview(string option)
        {
            var value = EventOperationPreview.Build(snapshot, option);
            Require(value.Faults.IsEmpty, ev.Id.Entry + "/" + option + " projection failed: " +
                string.Join(";", value.Faults.Select(f => f.Exception.ToString())));
            return value;
        }
        switch (ev.Id.Entry)
        {
            case "RANWID_THE_ELDER":
                var trade = PredictorOperation.Preview(snapshot, new ChooseEventOption("RELIC"));
                Require(trade.Effects.Any(e => e.Action == "RemoveRelic") && trade.Disposition == PredictorInputResult.Accepted,
                    "Ranwid live relic exchange did not settle detached removal");
                Preview("RELIC");
                break;
            case "RELIC_TRADER":
                var coffer = Preview("TOP");
                Require(Rows(coffer).Where(r => r.Action == OperationPreviewAction.GeneratePotion).Sum(r => r.Models.Length) == 4,
                    "Alchemical Coffer actual event projection must retain all four generated potions including overflow");
                foreach (string option in new[] { "TOP", "MIDDLE", "BOTTOM" })
                {
                    var preview = Preview(option);
                    Require(!Rows(preview).Any(r => r.Action == OperationPreviewAction.ObtainRelic),
                        "Trader repeated public relic identity");
                    if (option != "TOP") Require(Rows(preview).Any(r => r.Action == OperationPreviewAction.UpgradeCard && !r.Cards.IsEmpty),
                        "Trader Whetstone/WarPaint downstream upgrades missing");
                }
                break;
            case "HUNGRY_FOR_MUSHROOMS":
                var mushroom = Preview("FRAGRANT_MUSHROOM");
                Require(Rows(mushroom).Any(r => r.Action == OperationPreviewAction.UpgradeCard && !r.Cards.IsEmpty) &&
                    !Rows(mushroom).Any(r => r.Action == OperationPreviewAction.ObtainRelic),
                    "Fragrant Mushroom live random upgrade targets missing/public relic repeated");
                break;
            case "THE_LANTERN_KEY":
                var lantern = Preview("KEEP_THE_KEY");
                Require(lantern.Notices.Contains("EventCombatStableContextNoExtraActions") && lantern.Branches
                    .SelectMany(b => b.Sections).Any(s => s.Label == "EventCombatRewards" && !s.CardGroups.IsEmpty),
                    "Lantern live battle reward forecast missing");
                break;
            case "ROOM_FULL_OF_CHEESE":
                Require(Preview("SEARCH").Branches.IsEmpty && !Preview("GORGE").Branches.IsEmpty,
                    "Cheese public Search/random Gorge visibility differs");
                break;
            case "TRIAL":
                Require(Preview("ACCEPT").Branches.IsEmpty && Preview("REJECT").Branches.IsEmpty,
                    "Trial entrance showed a verdict before the actual case");
                break;
            case "DENSE_VEGETATION":
                var dense = Preview("REST");
                var denseSections = dense.Branches.SelectMany(b => b.Sections).ToArray();
                Require(denseSections.Any(s => s.Label == "EventRestRewards" && !s.CardGroups.IsEmpty) &&
                    denseSections.Any(s => s.Label == "EventCombatRewards" && !s.CardGroups.IsEmpty) &&
                    dense.Notices.Contains("EventCombatNoInterveningRewardClaims"),
                    "Dense live rest/battle rewards lost separate phases or stable inventory premise");
                break;
            case "WAR_HISTORIAN_REPY":
                Require(Preview("INITIAL_UNLOCK_CAGE").Branches.IsEmpty && !Preview("INITIAL_UNLOCK_CHEST").Branches.IsEmpty,
                    "Repy public history lesson/random chest visibility differs");
                break;
        }
    }

    private static void CheckPotionTargets(RunState native, Player actor)
    {
        var peer = native.Players.Single(p => p != actor);
        string StampTargets() => JsonSerializer.Serialize(new
        { Players = native.Players.Select(p => p.ToSerializable()).ToArray(), Rng = native.Rng.ToSerializable() },
            new JsonSerializerOptions { IncludeFields = true });
        string before = StampTargets();
        var own = PredictorOperationPotionTargetCapture.Capture(native, actor.NetId, "0.111.0");
        var other = PredictorOperationPotionTargetCapture.Capture(native, peer.NetId, "0.111.0");
        var ownOperation = own.Operation ?? throw new InvalidOperationException("OPERATION_EVENT_CAPTURE actor potion context missing");
        var peerOperation = other.Operation ?? throw new InvalidOperationException("OPERATION_EVENT_CAPTURE peer potion context missing");
        var ownPools = ownOperation.CombatCardPools ?? throw new InvalidOperationException("OPERATION_EVENT_CAPTURE actor potion pools missing");
        var peerPools = peerOperation.CombatCardPools ?? throw new InvalidOperationException("OPERATION_EVENT_CAPTURE peer potion pools missing");
        Require(own.Character == PredictorLiveRunCapture.Key(actor.Character) && other.Character == PredictorLiveRunCapture.Key(peer.Character) &&
            ownOperation.PlayerId == actor.NetId && peerOperation.PlayerId == peer.NetId && peerOperation.PlayerSlot == 1 &&
            other.Live == null && other.Crystal == null, "explicit potion context did not use selected native target");
        var nativeRng = native.Rng.CombatCardGeneration.ToSerializable();
        var expectedRng = new PredictorOperationEventRng(nativeRng.state0, nativeRng.state1, nativeRng.state2, nativeRng.state3, nativeRng.counter);
        Require(ownOperation.CombatCardRng == expectedRng && peerOperation.CombatCardRng == expectedRng,
            "potion targets must share actual CombatCardGeneration cursor");
        var constraint = ((IRunState)native).CardMultiplayerConstraint;
        Require(peerPools.CharacterCards.Select(c => c.Card.Key).SequenceEqual(
            peer.Character.CardPool.GetUnlockedCards(peer.UnlockState, constraint).Select(PredictorLiveRunCapture.Key)) &&
            ownPools.CharacterCards.Select(c => c.Card.Key).SequenceEqual(
            actor.Character.CardPool.GetUnlockedCards(actor.UnlockState, constraint).Select(PredictorLiveRunCapture.Key)),
            "potion context changed target's ordered unlocked character pool");
        var ownOrobic = PredictorOperationPotionQueries.Query(own, new("POTION", "OROBIC_ACID"));
        var peerOrobic = PredictorOperationPotionQueries.Query(other, new("POTION", "OROBIC_ACID"));
        var peerPool = peerPools.CharacterCards.Select(c => c.Card.Key).ToHashSet();
        Require(ownOrobic.IdentitiesComputed && peerOrobic.IdentitiesComputed && peerOrobic.TargetPlayerId == peer.NetId &&
            ownOrobic.Cards.Length == 3 && peerOrobic.Cards.Length == 3 &&
            peerOrobic.Cards.All(c => peerPool.Contains(c.Card.Key)) &&
            !peerOrobic.Cards.Select(c => c.Card.Key).SequenceEqual(ownOrobic.Cards.Select(c => c.Card.Key)),
            "Orobic explicit teammate query reused actor character pool");
        var ownCosmic = PredictorOperationPotionQueries.Query(own, new("POTION", "COSMIC_CONCOCTION"));
        var peerCosmic = PredictorOperationPotionQueries.Query(other, new("POTION", "COSMIC_CONCOCTION"));
        Require(peerCosmic.TargetPlayerId == peer.NetId && peerCosmic.Cards.Length == 3 &&
            peerCosmic.Cards.All(c => c.Card.UpgradeLevel == c.Card.MaxUpgradeLevel) &&
            peerCosmic.Cards.Select(c => c.Card.Key).SequenceEqual(ownCosmic.Cards.Select(c => c.Card.Key)),
            "Cosmic must use selected target's colorless unlocks and shared cursor");
        bool invalid = false;
        try { PredictorOperationPotionTargetCapture.Capture(native, ulong.MaxValue, "0.111.0"); }
        catch (ArgumentException) { invalid = true; }
        Require(invalid && StampTargets() == before, "potion target capture/query mutated native state or accepted foreign player");
    }

    private static void CheckMendTargets(RunState native, Player actor)
    {
        var peer = native.Players.Single(p => p != actor);
        int oldHp = peer.Creature.CurrentHp, oldMax = peer.Creature.MaxHp;
        bool oldActive = peer.IsActiveForHooks;
        var pillow = ModelDb.GetById<RelicModel>(new("RELIC", "REGAL_PILLOW")).ToMutable();
        var humidifier = ModelDb.GetById<RelicModel>(new("RELIC", "STONE_HUMIDIFIER")).ToMutable();
        peer.AddRelicInternal(pillow, silent: true);
        peer.AddRelicInternal(humidifier, silent: true);
        try
        {
            peer.Creature.SetMaxHpInternal(81);
            peer.Creature.SetCurrentHpInternal(10);
            peer.ActivateHooks();
            var facts = PredictorOperationMendCapture.CaptureTargets(native, actor);
            Require(facts.Length == 1 && facts[0] is
                { PlayerId: 2, CurrentHp: 10, MaximumHp: 81, RegalPillows: 1, StoneHumidifiers: 1, ActiveForHooks: true },
                "Mend target facts must belong to actual recipient, not actor inventory");
            decimal actualHeal = MegaCrit.Sts2.Core.Entities.RestSite.MendRestSiteOption.GetHealAmount(peer);
            Require(actualHeal == 39.3m && peer.Creature.CurrentHp == 10,
                "Mend actual vanilla Pillow amount differs or target capture healed recipient");
            peer.Creature.SetCurrentHpInternal(0);
            peer.DeactivateHooks();
            var dead = PredictorOperationMendCapture.CaptureTargets(native, actor).Single();
            Require(!dead.ActiveForHooks && dead.CurrentHp == 0 && dead.RegalPillows == 1 &&
                MegaCrit.Sts2.Core.Entities.RestSite.MendRestSiteOption.GetHealAmount(peer) == 24.3m && facts[0].CurrentHp == 10,
                "Mend must capture inactive recipient hooks and preserve previous detached facts");
            // These are the original command's HP/hook primitives on this
            // isolated fixture: resurrection precedes AfterRestSiteHeal.
            peer.Creature.HealInternal(24.3m);
            Require(peer.Creature.CurrentHp == 24 && peer.IsActiveForHooks,
                "original HealInternal did not reactivate revived recipient hooks");
            MegaCrit.Sts2.Core.Hooks.Hook.AfterRestSiteHeal(native, peer, false).GetAwaiter().GetResult();
            Require(peer.Creature.CurrentHp == 29 && peer.Creature.MaxHp == 86,
                "original recipient AfterRestSiteHeal did not apply Humidifier after revival");
        }
        finally
        {
            peer.RemoveRelicInternal(humidifier, silent: true);
            peer.RemoveRelicInternal(pillow, silent: true);
            peer.Creature.SetMaxHpInternal(oldMax);
            peer.Creature.SetCurrentHpInternal(oldHp);
            if (oldActive) peer.ActivateHooks(); else peer.DeactivateHooks();
        }
    }

    private static void Progressed(RunState native, EventModel ev, PredictorCatalog catalog, PredictorOperationEventScene initial)
    {
        switch (ev.Id.Entry)
        {
            case "THE_LANTERN_KEY":
                Invoke(ev, "KeepTheKey");
                var fight = CaptureUnchanged(native, ev, catalog);
                var baseline = PredictorOperationCapture.Capture(native, "0.111.0");
                Require(fight.Options.Single().Key == "FIGHT" &&
                    EventOperationPreview.Build(baseline with { Scene = fight }, "FIGHT").Faults.IsEmpty,
                    "Lantern progressed native fight page lost combat forecast");
                break;
            case "SLIPPERY_BRIDGE":
                var deck = ev.Owner!.Deck.Cards;
                Set(ev, "_numberOfHoldOns", 3);
                ev.DynamicVars["HpLoss"].BaseValue = 6;
                Set(ev, "_randomCardToLose", deck[0]);
                Set(ev, "_skippedRemovals", new HashSet<CardModel> { deck[1] });
                SetOptions(ev, ("SLIPPERY_BRIDGE.pages.INITIAL.options.OVERCOME", "Overcome"),
                    ("SLIPPERY_BRIDGE.pages.HOLD_ON_2.options.HOLD_ON_3", "HoldOn"));
                ev.Rng.NextInt(13);
                var bridge = CaptureUnchanged(native, ev, catalog);
                Require(bridge.BridgeHoldOns == 3 && bridge.BridgeCard == PredictorLiveRunCapture.Id(deck[0]) &&
                    bridge.BridgeSkipped.SetEquals([PredictorLiveRunCapture.Id(deck[1])]) &&
                    bridge.Options.Single(o => o.Key == "HOLD_ON").HealthDamage == 6 && bridge.Rng != initial.Rng,
                    "Bridge progressed fields were reset or replayed");
                break;
            case "TABLET_OF_TRUTH":
                Set(ev, "_decipherCount", 2);
                ev.DynamicVars["DecipherMaxHpLoss"].BaseValue = 12;
                SetOptions(ev, ("TABLET_OF_TRUTH.pages.DECIPHER_2.options.DECIPHER", "Decipher"),
                    ("TABLET_OF_TRUTH.pages.DECIPHER.options.GIVE_UP", "GiveUp"));
                ev.Rng.NextInt(13);
                var tablet = CaptureUnchanged(native, ev, catalog);
                Require(tablet.TabletCount == 2 && tablet.Options.Single(o => o.Key == "DECIPHER").MaxHpCost == 12,
                    "Tablet current count was replaced with entry count");
                break;
            case "ENDLESS_CONVEYOR":
                Set(ev, "_numOfGrabs", 4);
                Invoke(ev, "RollDish");
                var grab = (EventOption)ev.GetType().GetMethod("GenerateGrabSomethingOffTheBeltOption", Members)!.Invoke(ev, null)!;
                var leave = new EventOption(ev, (Func<Task>)ev.GetType().GetMethod("Leave", Members)!.CreateDelegate(typeof(Func<Task>), ev),
                    "ENDLESS_CONVEYOR.pages.GRAB_SOMETHING_OFF_THE_BELT.options.LEAVE");
                typeof(EventModel).GetField("_currentOptions", Members)!.SetValue(ev, new List<EventOption> { grab, leave });
                var conveyor = CaptureUnchanged(native, ev, catalog);
                Require(conveyor.ConveyorGrabs == 5 && conveyor.ConveyorDish == "SEAPUNK_SALAD",
                    "Conveyor fixed fifth dish was rerolled");
                break;
            case "TINKER_TIME":
                Invoke(ev, "ChooseCardType");
                var types = CaptureUnchanged(native, ev, catalog);
                Require(types.Options.Length == 2 && types.Options.All(o => o.Key is "ATTACK" or "SKILL" or "POWER"), "Tinker type stage");
                Invoke(ev, types.Options[0].Key switch { "ATTACK" => "Attack", "SKILL" => "Skill", _ => "Power" });
                var riders = CaptureUnchanged(native, ev, catalog);
                Require(riders.TinkerType != null && riders.Options.Length == 2, "Tinker rider stage lost chosen type");
                var tinkerSnapshot = PredictorOperationCapture.Capture(native, "0.111.0") with { Scene = riders };
                Require(riders.Options.All(option => EventOperationPreview.Build(tinkerSnapshot, option.Key).Branches.IsEmpty),
                    "Tinker actual final native previews were duplicated");
                break;
            case "TRIAL":
                ulong? local = LocalContext.NetId;
                try
                {
                    // The option logic's local VFX branch assumes an on-screen
                    // event room. This isolated native fixture has no UI.
                    LocalContext.NetId = native.Players.First(p => p != ev.Owner).NetId;
                    Invoke(ev, "Accept");
                }
                finally { LocalContext.NetId = local; }
                var trial = CaptureUnchanged(native, ev, catalog);
                Require(trial.Options.Length == 2 && trial.Options.All(o => o.Key.StartsWith("MERCHANT_", StringComparison.Ordinal) ||
                    o.Key.StartsWith("NOBLE_", StringComparison.Ordinal) || o.Key.StartsWith("NONDESCRIPT_", StringComparison.Ordinal)),
                    "Trial case source labels were not preserved");
                SetOptions(ev, ("TRIAL.pages.NONDESCRIPT.options.GUILTY", "NondescriptGuilty"),
                    ("TRIAL.pages.NONDESCRIPT.options.INNOCENT", "NondescriptInnocent"));
                var nondescript = CaptureUnchanged(native, ev, catalog);
                var trialSnapshot = PredictorOperationCapture.Capture(native, "0.111.0") with { Scene = nondescript };
                string trialBefore = Stamp(native, ev);
                var trialTransform = PredictorOperation.Preview(trialSnapshot, new ChooseEventOption("NONDESCRIPT_INNOCENT"));
                Require(trialTransform.Waiting.Selection.CandidateCardIds.Any(id =>
                    !trialSnapshot.State.Deck.Contains(id) && trialTransform.State.Card(id).Key.Entry == "DOUBT") &&
                    !EventOperationPreview.Build(trialSnapshot, "NONDESCRIPT_GUILTY").Branches.IsEmpty &&
                    !EventOperationPreview.Build(trialSnapshot, "NONDESCRIPT_INNOCENT").Branches.IsEmpty &&
                    Stamp(native, ev) == trialBefore,
                    "Actual Trial verdict capture lost hidden rewards/new curse targets or mutated the native run");
                Invoke(ev, "Reject");
                var rejected = CaptureUnchanged(native, ev, catalog);
                Require(rejected.Options.Select(o => o.Key).SequenceEqual(["ACCEPT", "DOUBLE_DOWN"]),
                    "Trial legal proceed-style DoubleDown option was hidden");
                // Native DoubleDown is re-clickable after cancel; WasChosen
                // remains true because DisableOnChosen=false.
                typeof(EventOption).GetField("<WasChosen>k__BackingField", Members)!.SetValue(
                    ev.CurrentOptions.Single(o => o.TextKey.EndsWith(".DOUBLE_DOWN", StringComparison.Ordinal)), true);
                Require(CaptureUnchanged(native, ev, catalog).Options.Any(o => o.Key == "DOUBLE_DOWN"),
                    "Canceled Trial confirmation became an in-flight action");
                break;
            case "THE_FUTURE_OF_POTIONS":
                Require(initial.FuturePotionTypes.Count == ev.Owner!.Potions.Count() &&
                    initial.FuturePotionRarities.Count == initial.FuturePotionTypes.Count &&
                    initial.Options.All(o => o.PotionId is { } id && initial.FuturePotionTypes[id] == o.CardType),
                    "Future actual per-instance mapping missing");
                break;
            case "WAR_HISTORIAN_REPY":
                var owner = ev.Owner!;
                for (int i = 0; i < 2; i++)
                {
                    var key = ModelDb.GetById<CardModel>(new("CARD", "LANTERN_KEY")).ToMutable();
                    native.AddCard(key, owner); owner.Deck.AddInternal(key);
                }
                ulong? originalLocal = LocalContext.NetId;
                try
                {
                    // Run the original key-removal helper with the other local
                    // identity so deck preview nodes are unnecessary here.
                    LocalContext.NetId = native.Players.First(p => p != owner).NetId;
                    Invoke(ev, "RemoveLanternKeysForInitialChoice");
                }
                finally { LocalContext.NetId = originalLocal; }
                Require(native.Players.Count > 1 && !owner.Deck.Cards.Any(c => c.Id.Entry == "LANTERN_KEY") &&
                    !(bool)ev.GetType().GetProperty("ShouldGetSecondReward", Members)!.GetValue(ev)!,
                    "Original multiplayer Repy did not remove every key and suppress second choice");
                CaptureUnchanged(native, ev, catalog);
                break;
        }
    }

    private static PredictorOperationEventScene CaptureUnchanged(RunState native, EventModel ev, PredictorCatalog catalog)
    {
        string before = Stamp(native, ev);
        var scene = (PredictorOperationEventScene)PredictorOperationEventCapture.Capture(native, ev, catalog);
        Require(Stamp(native, ev) == before, ev.Id.Entry + " progressed capture mutated fixture");
        return scene;
    }

    private static string Stamp(RunState native, EventModel ev) => JsonSerializer.Serialize(new
    {
        Players = native.Players.Select(p => p.ToSerializable()).ToArray(), Rng = native.Rng.ToSerializable(),
        EventRng = ev.Rng.ToSerializable(), Options = ev.CurrentOptions.Select(o => new { o.TextKey, o.IsLocked, o.WasChosen }).ToArray(),
        Bag = PredictorLiveRunCapture.Bag(native.SharedRelicGrabBag),
        Personal = native.Players.Select(p => PredictorLiveRunCapture.Bag(p.RelicGrabBag)).ToArray()
    }, new JsonSerializerOptions { IncludeFields = true });
    private static void Set(object owner, string field, object value) => owner.GetType().GetField(field, Members)!.SetValue(owner, value);
    private static void SetOptions(EventModel ev, params (string Key, string Method)[] options) =>
        typeof(EventModel).GetField("_currentOptions", Members)!.SetValue(ev, options.Select(o => new EventOption(ev,
            (Func<Task>)ev.GetType().GetMethod(o.Method, Members)!.CreateDelegate(typeof(Func<Task>), ev), o.Key)).ToList());
    private static void Invoke(EventModel ev, string method)
    {
        if (ev.GetType().GetMethod(method, Members)!.Invoke(ev, null) is Task task) task.GetAwaiter().GetResult();
    }
    private static void Require(bool condition, string detail)
    { if (!condition) throw new InvalidOperationException("OPERATION_EVENT_CAPTURE " + detail); }
