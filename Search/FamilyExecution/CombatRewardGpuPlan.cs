using RolltheSpire2.Compatibility;
using RolltheSpire2.Core.Identity;
using RolltheSpire2.Search.Contracts;
using RolltheSpire2.Search.FamilyExecution;

namespace RolltheSpire2.Search.FamilyExecution;

internal sealed record CombatRewardGpuPlan(uint[] Meta, uint[] Pools, uint[] Ids, uint[] Predicates,
    uint[] Targets, Beta110GpuCombatRewardHotLoopPlan HotLoop, int Routes)
{
    internal GpuNumericalVariant NumericalVariant { get; init; }
    internal GpuNumericRequirements NumericRequirements => GpuIntegerNumerics.Requirements(NumericalVariant);
    internal bool UsesHotLoop => HotLoop.Enabled;
    internal bool NeedsCompleteMatchingReference { get; init; }
    // Historical MP-C2 metadata retained for old evidence formatters. The
    // query-literal body allocates no Capsule bag and has no capacity variant.
    internal const bool FactoryExactBagCapacity = true;
    internal bool ExactBagCapacity { get; init; }
    internal string BagCapacityRevision => BagCapacity != 512
        ? ".ExactBagCapacity.20261016.v1.Slot" + Meta[2] + ".Entries" + BagCapacity : "";
    // Stable old empty-bag shape value; no bag storage is generated by C.
    internal int BagCapacity => 512;
    internal bool UsesQueryLiteralPartyOpening { get; init; }
    internal string TerminalCardGateSource { get; init; } = "";
    internal bool UsesTerminalCardGate => TerminalCardGateSource.Length != 0;
    internal string Revision(bool compact) => "C.CombatReward.Gpu." + (UsesHotLoop ? "NeutralHotLoop" : "GenericStreaming.EmptyExclusionDirect.20261013.v1") +
        (UsesTerminalCardGate ? ".TerminalCardCapacity.20261015.v1" : "") +
        (NeedsCompleteMatchingReference ? ".CompletePositiveMatching.20261026.v1" : "") +
        (UsesQueryLiteralPartyOpening ? ".PartyQueryLiteralOpening.20261027.v1" : "") +
        BagCapacityRevision +
        (compact ? ".CompactAbi1" : ".Dense") + ".CanonicalAbi1Ready.20260907.v1" +
        (NumericalVariant == GpuNumericalVariant.IntegerRne ? ".IntegerRne.20261025.v1" : "") + GpuRngRotation.Revision;

    internal static CombatRewardGpuPlan? TryCreate(ExactSearchExecutionRequest request, CombatRewardReplay replay, out string issue)
    {
        issue = "";
        var reward = replay.Plan;
        // Physical bounds of the retained donor, not Search admission gates.
        if (!RuntimeProfilePolicies.UsesBeta110SharedAlgorithms(request.ProfileId)) issue = "RootCodecOutsideDonor";
        else if (reward.PredicateCount > 64) issue = "PredicateMaskCapacity";
        else if (reward.OpeningConsumption.OrderedRelicIds.Contains(Beta110FastRelicCatalog.Kaleidoscope) &&
            !replay.KaleidoscopeCountOnly && replay.Catalog.OtherCharacterPools.Length > 15) issue = "KaleidoscopePermutationCapacity";
        if (issue.Length != 0) return null;
        var catalog = replay.Catalog with { OrdinaryRelics = [], PlayerRelicBuckets = [], SharedRelicConsumeShuffleLengths = [] };
        var policy = Beta110GpuCombatRewardRoutePolicy.UnpinnedAssumeUnperturbed;
        var hot = Beta110GpuCombatRewardHotLoopCompiler.Compile(request.Ascension, reward, catalog, policy);
        uint[] meta = CombatRewardGpuPacking.BuildPlanMeta(request.Authority.PlayerSlotIndex,
            request.Authority.PlayersCount, request.Ascension, request.Authority.AllCharacterCardPoolsUnlocked == true,
            request.Authority.IsScrollBoxesAllowed == true, request.CharacterKey == BaseGameModelKeys.Characters.Defect,
            request.Authority.EffectAuthority?.BonesEligibleRelics?.Count(k => k != BaseGameModelKeys.Relics.NeowsBones) ?? 0,
            reward, 0x43463031, catalog, policy, 255, 255, 255, hot, replay.PrecedingNicheDraws,
            replay.CapsuleNicheAdvances, replay.KaleidoscopeCountOnly, replay.ConservativelyKeeps);
        uint[] pools = CombatRewardGpuPacking.BuildPoolMeta(catalog, out uint[] ids);
        uint[] predicates = CombatRewardGpuPacking.BuildPredicates(reward, out uint[] targets);
        return new(meta, pools, ids, predicates, targets, hot, replay.RouteCount) {
            NeedsCompleteMatchingReference = reward.NeedsCompleteMatchingReference,
            UsesQueryLiteralPartyOpening = replay.UsesQueryLiteralPartyOpening,
            ExactBagCapacity = FactoryExactBagCapacity,
            TerminalCardGateSource = CompileTerminalCardGate(request, replay, hot.Enabled)
        };
    }

    private static string CompileTerminalCardGate(ExactSearchExecutionRequest request, CombatRewardReplay replay, bool hot)
    {
        var plan = replay.Plan;
        if (hot || request.Authority.PlayersCount != 1 || replay.ConservativelyKeeps ||
            !plan.CardPoolAuthorityExact) return "";
        // The gate skips only the terminal battle's remaining ordinary cards.
        // Three distinct identities across the fallback pools prove those draws
        // cannot fault, even when a rarity pool is empty or contains duplicates.
        var pool = replay.Catalog.CombatRewardCardPool;
        if (pool.Common.Concat(pool.Uncommon).Concat(pool.Rare)
            .Where(id => id != Beta110FastDenseId.Invalid).Distinct().Take(3).Count() < 3) return "";
        var targets = new Dictionary<ushort, ulong>();
        for (int i = 0; i < plan.Predicates.Length; i++)
        {
            var row = plan.Predicates[i];
            if (!row.HasCardPredicate) continue;
            if (!row.IsAnyBattle || row.CardAny.Length + row.CardAll.Length != 1 || row.CardBan.Length != 0 ||
                row.HasPotionDropPredicate || row.HasPotionIdentityPredicate || row.HasGoldPredicate) return "";
            ushort target = row.CardAny.Length == 1 ? row.CardAny[0] : row.CardAll[0];
            targets[target] = targets.GetValueOrDefault(target) | (1UL << i);
        }
        // One target cannot run out of slots before the original last draw.
        // Keep this first measured specialization bounded to small target sets.
        if (targets.Count is < 2 or > 6) return "";
        var source = new System.Text.StringBuilder("#ifndef RT2_C_TERMINAL_CARD_GATE\n#define RT2_C_TERMINAL_CARD_GATE 1\n#endif\n#if RT2_C_TERMINAL_CARD_GATE\nuint cr_terminal_card_missing(uint64_t matched){uint missing=0u;");
        int bit = 0;
        foreach (var (_, mask) in targets)
            source.Append($"if((matched&uint64_t(0x{mask:X}ul))==uint64_t(0u))missing|={1u << bit++}u;");
        source.Append("return missing;}\nuint cr_terminal_card_seen(uint missing,uint value){");
        bit = 0;
        foreach (var (target, _) in targets)
            source.Append($"if(value=={target}u)missing&=~{1u << bit++}u;");
        return source.Append("return missing;}\n#endif\n").ToString();
    }

    internal string ShaderSource(bool forceGeneric = false)
    {
        string source = FamilyGpuComputeUtility.LoadEmbeddedShader("CombatRewardFamily.comp.glsl")
        .Replace("/*__C_TERMINAL_CARD_GATE__*/", TerminalCardGateSource, StringComparison.Ordinal)
        .Replace("/*__C_CAPSULE_DEFINES__*/", "#define RT2_C_ASSIGNMENT " + (Meta[56] + Meta[59] > 0 ? "1\n" : "0\n") + "#define RT2_C_MULTIPLAYER " + (Meta[3] > 1 ? "1" : "0"), StringComparison.Ordinal)
        .Replace("/*__C_HOT_DEFINES__*/", Beta110GpuCombatRewardHotLoopCompiler.BuildShaderDefines(HotLoop,
            Beta110GpuCombatRewardRoutePolicy.UnpinnedAssumeUnperturbed, forceGeneric ? Beta110GpuCombatRewardHotLoopVariant.Disabled :
            Beta110GpuCombatRewardHotLoopVariant.OptimizedSingleRoute), StringComparison.Ordinal)
        .Replace("/*__C_COMMON__*/", FamilyGpuComputeUtility.LoadEmbeddedShader("Beta110GpuCombatRewardCommon.glsl"), StringComparison.Ordinal)
        .Replace("/*__C_STREAMING__*/", FamilyGpuComputeUtility.LoadEmbeddedShader("Beta110GpuCombatRewardStreamingP10A.glsl"), StringComparison.Ordinal);
        return NumericalVariant switch
        {
            GpuNumericalVariant.NativeFloat64 => source,
            GpuNumericalVariant.IntegerRne => CombatRewardIntegerSource.Adapt(source),
            _ => throw new InvalidOperationException("C.UnknownGpuNumericalVariant")
        };
    }
}
